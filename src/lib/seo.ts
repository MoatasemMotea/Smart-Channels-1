/** Home → … → the page, every item an absolute URL. `trail` excludes Home. */
export function breadcrumbSchema(opts: {
  locale: Locale;
  home: string;
  trail: { name: string; path: string }[];
}): Record<string, unknown> {
  const origin = siteUrl().origin;
  const items = [{ name: opts.home, path: "" }, ...opts.trail];
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((it, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: it.name,
      item: `${origin}/${opts.locale}${it.path}`,
    })),
  };
}
