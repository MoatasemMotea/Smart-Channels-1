import type { Metadata } from "next";
import type { Locale, SocialPlatform } from "@/types/content";
import { getContact, localize } from "@/lib/content";
import { LEGAL_NAME_AR } from "@/content/lang-allowlist";

/**
 * Indexing gate (Q-P3-11): everything is noindex unless the authorized
 * production deployment explicitly sets NEXT_PUBLIC_ALLOW_INDEXING=true.
 * A preview/test deployment can therefore never leak into search engines.
 */
export function indexingAllowed(): boolean {
  return process.env.NEXT_PUBLIC_ALLOW_INDEXING === "true";
}

export const SITE_NAME = "Smart Channels";
/** D-088 (SEO-6): the site name per locale — Arabic pages use the
 *  Arabic name in the title template and og:siteName */
export const SITE_NAME_AR = "القنوات الذكية";
export function siteName(locale: Locale): string {
  return locale === "ar" ? SITE_NAME_AR : SITE_NAME;
}

/**
 * The site origin that makes every metadata URL absolute (D-086):
 * NEXT_PUBLIC_SITE_URL when the owner sets it (the launch domain), else
 * Vercel's production URL (VERCEL_PROJECT_PRODUCTION_URL, set by Vercel
 * on its builds), else the local dev server. No domain is written here.
 */
export function siteUrl(): URL {
  const explicit = process.env.NEXT_PUBLIC_SITE_URL;
  if (explicit) return new URL(explicit);
  const vercel = process.env.VERCEL_PROJECT_PRODUCTION_URL;
  if (vercel) return new URL(`https://${vercel}`);
  return new URL("http://localhost:3000");
}

/** hreflang alternates for a route path (without locale prefix). */
export function localeAlternates(path: string): NonNullable<Metadata["alternates"]> {
  const p = path === "/" ? "" : path;
  return {
    canonical: undefined, // set per page with the locale prefix
    languages: {
      en: `/en${p}`,
      ar: `/ar${p}`,
      "x-default": `/ar${p}`, // D-088: Arabic is the default locale
    },
  };
}

/**
 * A meta description from approved text only (D-088 · SEO-5): the lead
 * sentence(s), then the place and the year, trimmed at a word boundary to
 * `max` characters. Nothing is invented: callers pass existing strings,
 * and an empty lead falls back to the place and year alone.
 */
export function composeDescription(lead: string[], tail: (string | null | undefined)[], max = 155): string {
  const t = tail.filter(Boolean).join(" · ");
  const body = lead.map((s) => s.trim()).filter(Boolean).join(" — ");
  if (!body) return t;
  const room = t ? max - t.length - 3 : max;
  let text = body;
  if (text.length > room) {
    const cut = text.slice(0, Math.max(0, room - 1));
    text = `${cut.slice(0, cut.lastIndexOf(" ") > 40 ? cut.lastIndexOf(" ") : cut.length).replace(/[\s,،—–-]+$/, "")}…`;
  }
  return t ? `${text} · ${t}` : text;
}

/**
 * The static share image for a locale (D-088 · SEO-10), generated by
 * scripts/generate-og.ts into public/og/. One per locale for now.
 * Relative — resolved against metadataBase (siteUrl) into an absolute URL.
 */
export function shareImage(locale: Locale) {
  return {
    url: `/og/og-${locale}.png`,
    width: 1200,
    height: 630,
    alt: locale === "ar" ? SITE_NAME_AR : SITE_NAME,
  };
}

/** openGraph.images + a large Twitter card — Next replaces (not merges)
 *  a parent's openGraph/twitter, so every metadata object carries both. */
export function shareMetadata(locale: Locale, title?: string, description?: string): Pick<Metadata, "twitter"> & {
  images: ReturnType<typeof shareImage>[];
} {
  const img = shareImage(locale);
  return {
    images: [img],
    twitter: { card: "summary_large_image", ...(title ? { title } : {}), ...(description ? { description } : {}), images: [img.url] },
  };
}

export function pageMetadata(opts: {
  locale: Locale;
  path: string;
  title: string;
  description: string;
}): Metadata {
  const p = opts.path === "/" ? "" : opts.path;
  const share = shareMetadata(opts.locale, opts.title, opts.description);
  return {
    title: opts.title,
    description: opts.description,
    alternates: {
      canonical: `/${opts.locale}${p}`,
      languages: localeAlternates(opts.path).languages,
    },
    robots: indexingAllowed() ? undefined : { index: false, follow: false },
    openGraph: {
      title: opts.title,
      description: opts.description,
      siteName: siteName(opts.locale),
      locale: opts.locale === "ar" ? "ar_SA" : "en_US",
      type: "website",
      // resolved against metadataBase (siteUrl) into an absolute URL
      url: `/${opts.locale}${p}`,
      images: share.images,
    },
    twitter: share.twitter,
  };
}

