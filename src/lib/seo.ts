/**
 * The authoritative brand artwork already shipped in /public (D-001),
 * made absolute against siteUrl() (D-088) — the origin comes from the
 * environment, never from a written-in domain.
 */
const ORGANIZATION_LOGO = "/brand/logo-dark.png";

/**
 * sameAs admits ORGANIZATION profiles only (D-055).
 *
 * On an Organization, schema.org `sameAs` asserts "this URL is another
 * official page OF THIS ENTITY". A personal/member profile is a
 * different entity (a Person), so listing one here would be a false
 * identity claim to search engines — even when the account is operated
 * by the company.
 *
 * The distinction is read from each platform's own URL grammar rather
 * than from a hand-maintained list of blocked URLs, so the rule keeps
 * working for links nobody has entered yet:
 *   - linkedin: organizations live under /company/, /showcase/ or
 *     /school/; /in/<slug> is a member (Person) profile.
 *   - facebook / instagram / x: people and organizations share one
 *     handle namespace, so the URL carries no signal and the record is
 *     taken at face value.
 *
 * TO REVERSE: delete the platform's entry below and every supplied URL
 * flows straight through to sameAs.
 */
const ORGANIZATION_PROFILE_PATH: Partial<Record<SocialPlatform, RegExp>> = {
  linkedin: /^\/(company|showcase|school)\//,
};

function isOrganizationProfile(platform: SocialPlatform, url: string): boolean {
  const shape = ORGANIZATION_PROFILE_PATH[platform];
  if (!shape) return true; // platform cannot express the distinction
  try {
    return shape.test(new URL(url).pathname);
  } catch {
    return false; // unparseable URL is never an identity claim
  }
}

/**
 * Official organization profiles, derived from the same single source of
 * truth the footer renders (`getContact().social`, D-091). Supplying a
 * real company URL in src/content/contact.ts fills this automatically —
 * a data edit only, no engineering (D-029/D-055).
 */
export function organizationSameAs(): string[] {
  const social = getContact().social;
  return (Object.entries(social) as [SocialPlatform, string | null][])
    .filter((entry): entry is [SocialPlatform, string] => entry[1] !== null)
    .filter(([platform, url]) => isOrganizationProfile(platform, url))
    .map(([, url]) => url);
}

/**
 * Organization JSON-LD built strictly from approved content (D-011): the
 * brand name, the shipped logo, and the contact block the footer already
 * renders. Optional schema fields whose data does not exist in the
 * project are omitted rather than invented — notably `url`, which waits
 * on an approved production domain (D-010).
 */
export function organizationSchema(opts: {
  locale: Locale;
  /** Localized brand name, from the same message key the footer uses. */
  name: string;
}): Record<string, unknown> {
  const contact = getContact();
  const sameAs = organizationSameAs();
  const origin = siteUrl().origin;
  const parts = contact.addressParts;
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: opts.name,
    // D-082 · D-088: the registered name in both locales; the other name as alternate
    legalName: LEGAL_NAME_AR,
    alternateName: opts.locale === "ar" ? SITE_NAME : SITE_NAME_AR,
    url: `${origin}/${opts.locale}`,
    logo: `${origin}${ORGANIZATION_LOGO}`,
    /* D-088 (SEO-11): the approved address split into its own parts
       (contact.addressParts) — no postal code, none is approved */
    address: parts
      ? {
          "@type": "PostalAddress",
          streetAddress: localize(parts.street, opts.locale),
          addressLocality: localize(parts.city, opts.locale),
          addressCountry: parts.country,
        }
      : localize(contact.address, opts.locale),
    telephone: contact.phone,
    email: contact.email,
    contactPoint: [
      {
        "@type": "ContactPoint",
        contactType: "customer service",
        telephone: contact.phone,
        email: contact.email,
        areaServed: "SA",
        availableLanguage: ["ar", "en"],
      },
    ],
    areaServed: "SA",
    /* An empty sameAs is worse than no sameAs — omit the field entirely
       until an organization profile exists (D-055 §3). */
    ...(sameAs.length > 0 ? { sameAs } : {}),
  };
}

